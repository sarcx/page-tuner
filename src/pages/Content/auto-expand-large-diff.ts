import {clickOn, isClicked} from './modules'

function findLoadDiffButton(entry: Element): HTMLButtonElement | null {
  const buttons = entry.querySelectorAll<HTMLButtonElement>('button')
  return Array.from(buttons).find(btn => btn.textContent?.trim() === 'Load Diff') ?? null
}

function getFileName(entry: Element): string | null {
  const code = entry.querySelector('h3 a code')
  return code?.textContent?.replace(/\u200e/g, '').trim() || null
}

function isAutoGenerated(fileName: string, autoGenerateFileNames: string[]): boolean {
  return autoGenerateFileNames.some(name => fileName.includes(name))
}

function isReviewed(entry: Element): boolean {
  const viewedBtn = entry.querySelector('button[aria-label="Viewed"], button[aria-label="Not Viewed"]')
  return viewedBtn?.getAttribute('aria-pressed') === 'true'
}

export function autoExpandLargeDiffs(autoGenerateFileNames: string[]): void {
  const entries = document.querySelectorAll<HTMLElement>('[id^="diff-"]')

  for (const entry of Array.from(entries)) {
    const loadButton = findLoadDiffButton(entry)
    if (!loadButton || isClicked(loadButton)) continue

    const fileName = getFileName(entry)
    if (!fileName || isAutoGenerated(fileName, autoGenerateFileNames)) continue
    if (isReviewed(entry)) continue

    clickOn(loadButton, fileName)
  }
}
