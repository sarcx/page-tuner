import {autoExpandLargeDiffs} from './auto-expand-large-diff'

const AUTO_GENERATED = ['schema.graphql', '.generated.ts', 'yarn.lock']

type DiffOpts = {file: string; reviewed?: boolean; collapsed?: boolean}

function diffEntry({file, reviewed = false, collapsed = true}: DiffOpts, index: number): string {
  const pressed = reviewed ? 'true' : 'false'
  const label = reviewed ? 'Viewed' : 'Not Viewed'
  const body = collapsed
    ? '<div class="HiddenDiffPatch"><button><span data-component="text">Load Diff</span></button></div>'
    : '<table><tbody><tr><td>code</td></tr></tbody></table>'

  return `
    <div id="diff-${index}">
      <h3><a href="#"><code>${file}</code></a></h3>
      <button aria-label="${label}" aria-pressed="${pressed}"><span data-component="text">Viewed</span></button>
      ${body}
    </div>`
}

function render(...diffs: DiffOpts[]) {
  document.body.innerHTML = diffs.map(diffEntry).join('')
}

function loadDiffButtonFor(index: number): HTMLButtonElement {
  const entry = document.getElementById(`diff-${index}`)!
  return Array.from(entry.querySelectorAll('button')).find(b => b.textContent?.trim() === 'Load Diff')!
}

describe('autoExpandLargeDiffs', () => {
  afterEach(() => {
    document.body.innerHTML = ''
  })

  it('expands a collapsed, unreviewed, non-generated file', () => {
    render({file: 'app/models/user.rb'})
    const click = jest.spyOn(loadDiffButtonFor(0), 'click')

    autoExpandLargeDiffs(AUTO_GENERATED)

    expect(click).toHaveBeenCalledTimes(1)
  })

  it('skips autogenerated files', () => {
    render({file: 'app/graphql/schema.graphql'})
    const click = jest.spyOn(loadDiffButtonFor(0), 'click')

    autoExpandLargeDiffs(AUTO_GENERATED)

    expect(click).not.toHaveBeenCalled()
  })

  it('skips already-reviewed files', () => {
    render({file: 'app/models/user.rb', reviewed: true})
    const click = jest.spyOn(loadDiffButtonFor(0), 'click')

    autoExpandLargeDiffs(AUTO_GENERATED)

    expect(click).not.toHaveBeenCalled()
  })

  it('ignores files that are not collapsed (no Load Diff button)', () => {
    render({file: 'app/models/user.rb', collapsed: false})

    expect(() => autoExpandLargeDiffs(AUTO_GENERATED)).not.toThrow()
  })

  it('only expands the eligible files in a mixed list', () => {
    render(
      {file: 'app/models/user.rb'},
      {file: 'app/graphql/schema.graphql'},
      {file: 'app/models/account.rb', reviewed: true},
      {file: 'app/services/importer.rb'}
    )
    const clicks = [0, 1, 2, 3].map(i => jest.spyOn(loadDiffButtonFor(i), 'click'))

    autoExpandLargeDiffs(AUTO_GENERATED)

    expect(clicks.map(c => c.mock.calls.length)).toEqual([1, 0, 0, 1])
  })

  it('does not click the same button twice across runs', () => {
    render({file: 'app/models/user.rb'})
    const click = jest.spyOn(loadDiffButtonFor(0), 'click')

    autoExpandLargeDiffs(AUTO_GENERATED)
    autoExpandLargeDiffs(AUTO_GENERATED)

    expect(click).toHaveBeenCalledTimes(1)
  })
})
