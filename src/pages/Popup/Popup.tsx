import React, {ChangeEvent, ReactNode, useEffect, useState} from 'react'
import {getRuleDefinitions} from '../utils/messages'
import './Popup.css'

const STORAGE_KEY = 'pageTunerRules'

type RuleItem = {key: string; label: ReactNode}

const SECTIONS: {title: string; rules: RuleItem[]}[] = [
  {
    title: 'GitHub',
    rules: [
      {key: 'autoCollapseRule', label: 'Auto review and collapse autogenerated files'},
      {key: 'moveCompareButtonRule', label: 'Move out Compare and Open pull request buttons'},
      {
        key: 'markFileAsViewedRule',
        label: (
          <>
            Mark file as viewed <kbd>Shift</kbd>
            <kbd>Space</kbd>
          </>
        )
      },
      {key: 'autoExpandLargeDiffRule', label: 'Auto expand large diffs'},
      {key: 'goToLineInEditorRule', label: 'Go to line in editor'},
      {key: 'copyFileNameRule', label: 'Copy file name from review threads'},
      {key: 'copyReviewLinksRule', label: 'Copy comment link & path in review threads'},
      {key: 'submitReviewShortcutsRule', label: 'Approve & 👁 shortcuts next to Submit review'},
      {key: 'highlightSelectionRule', label: 'Highlight selection'}
    ]
  },
  {
    title: 'Peakon',
    rules: [{key: 'peakonRememberAnswersRule', label: 'Remember survey answers'}]
  }
]

const RULE_COUNT = SECTIONS.reduce((count, section) => count + section.rules.length, 0)

function parseRepoMappings(text: string): Record<string, string> {
  const mappings: Record<string, string> = {}
  for (const line of text.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || !trimmed.includes('=')) continue
    const [repo, ...rest] = trimmed.split('=')
    const repoKey = repo.trim()
    const pathValue = rest.join('=').trim()
    if (repoKey && pathValue) mappings[repoKey] = pathValue
  }
  return mappings
}

// Reads the stored rules fresh before writing so a save never clobbers another rule's state.
function saveRule(key: string, enabled: boolean, specifics?: Record<string, any>) {
  getRuleDefinitions().then(rules => {
    chrome.storage.local.set({
      [STORAGE_KEY]: {
        ...rules,
        [key]: {enabled, specifics: specifics || rules[key]?.specifics || {}}
      }
    })
  })
}

function Popup() {
  const [enabled, setEnabled] = useState<Record<string, boolean>>({})
  const [repoMappingsText, setRepoMappingsText] = useState<string>('')

  useEffect(() => {
    getRuleDefinitions().then(rules => {
      setEnabled(Object.fromEntries(Object.entries(rules).map(([key, rule]) => [key, !!rule?.enabled])))

      const mappings: Record<string, string> = rules.goToLineInEditorRule?.specifics?.repoMappings || {}
      setRepoMappingsText(
        Object.entries(mappings)
          .map(([repo, path]) => `${repo} = ${path}`)
          .join('\n')
      )
    })
  }, [])

  const onToggle = (key: string, value: boolean) => {
    setEnabled(current => ({...current, [key]: value}))
    saveRule(key, value)
  }

  const onChangeRepoMappings = (e: ChangeEvent<HTMLTextAreaElement>): void => {
    setRepoMappingsText(e.target.value)
    saveRule('goToLineInEditorRule', !!enabled.goToLineInEditorRule, {
      repoMappings: parseRepoMappings(e.target.value)
    })
  }

  const enabledCount = SECTIONS.flatMap(section => section.rules).filter(rule => enabled[rule.key]).length

  return (
    <main className="popup">
      <header className="header">
        <img src="icon-128.png" width="32" height="32" alt="" />
        <div>
          <h1>Page Tuner</h1>
          <p>
            {enabledCount} of {RULE_COUNT} rules on
          </p>
        </div>
      </header>

      {SECTIONS.map(section => (
        <section key={section.title}>
          <h2>{section.title}</h2>
          <ul className="card">
            {section.rules.map(rule => (
              <li key={rule.key}>
                <label className="row">
                  <span className="row-label">{rule.label}</span>
                  <Switch value={!!enabled[rule.key]} onChange={value => onToggle(rule.key, value)} />
                </label>
                {rule.key === 'goToLineInEditorRule' && enabled.goToLineInEditorRule && (
                  <div className="row-extra">
                    <span className="hint">
                      Repo mappings, one per line: <code>org/repo = /local/path</code>
                    </span>
                    <textarea
                      value={repoMappingsText}
                      onChange={onChangeRepoMappings}
                      placeholder="myorg/my-repo = /Users/me/Projects/my-repo"
                      rows={3}
                      spellCheck={false}
                    />
                  </div>
                )}
              </li>
            ))}
          </ul>
        </section>
      ))}
    </main>
  )
}

function Switch({value, onChange}: {value: boolean; onChange: (value: boolean) => void}) {
  return (
    <span className="switch">
      <input type="checkbox" role="switch" checked={value} onChange={e => onChange(e.target.checked)} />
      <span className="slider" aria-hidden="true" />
    </span>
  )
}

export default Popup
